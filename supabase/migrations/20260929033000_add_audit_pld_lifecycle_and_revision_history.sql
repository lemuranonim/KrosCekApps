grant execute on function public.refresh_audit_pld_lifecycle_for_field(text, uuid)
  to service_role;

create or replace function public.refresh_audit_pld_after_act_field_update()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_run_id uuid;
begin
  if old.effective_area_ha is not distinct from new.effective_area_ha then
    return new;
  end if;

  select run.id
  into v_run_id
  from public.act_sync_changes change
  join public.act_sync_runs run on run.id = change.run_id
  where change.field_number_norm = upper(
      regexp_replace(btrim(new.field_number), '[[:space:]]+', '', 'g')
    )
    and change.changed_columns ? 'effective_area_ha'
    and run.dry_run = false
    and run.status in ('APPLYING', 'COMPLETED')
  order by run.started_at desc
  limit 1;

  if v_run_id is not null then
    perform public.refresh_audit_pld_lifecycle_for_field(
      new.field_number,
      v_run_id
    );
  end if;

  return new;
end;
$$;

