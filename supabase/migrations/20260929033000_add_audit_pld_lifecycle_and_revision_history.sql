create table if not exists public.audit_pld_lifecycle (
  field_number text not null,
  phase_key text not null check (
    phase_key in (
      'vegetative',
      'generative_1',
      'generative_2',
      'generative_3',
      'generative_4',
      'generative_5',
      'pre_harvest',
      'harvest'
    )
  ),
  status text not null check (status in ('PENDING', 'CONFIRMED', 'UPDATED')),
  recommendation_payload jsonb not null default '{}'::jsonb,
  recommended_flagging text,
  active_flagging text,
  effective_area_ha numeric,
  recommended_at timestamptz not null default now(),
  recommended_by uuid,
  confirmed_at timestamptz,
  confirmed_run_id uuid references public.act_sync_runs(id) on delete set null,
  revised_at timestamptz,
  revised_by uuid,
  updated_at timestamptz not null default now(),
  primary key (field_number, phase_key)
);

create table if not exists public.audit_revision_history (
  id bigint generated by default as identity primary key,
  field_number text not null,
  phase_key text not null,
  audit_table text not null,
  event_type text not null check (
    event_type in (
      'CREATED',
      'UPDATED',
      'BACKFILLED',
      'ACT_CONFIRMED',
      'ACT_REOPENED'
    )
  ),
  old_payload jsonb not null default '{}'::jsonb,
  new_payload jsonb not null default '{}'::jsonb,
  old_flagging text,
  new_flagging text,
  lifecycle_status text check (
    lifecycle_status is null
    or lifecycle_status in ('PENDING', 'CONFIRMED', 'UPDATED')
  ),
  actor_id uuid,
  actor_name text,
  actor_role text,
  act_sync_run_id uuid references public.act_sync_runs(id) on delete set null,
  created_at timestamptz not null default now()
);

create index if not exists audit_pld_lifecycle_status_idx
  on public.audit_pld_lifecycle (status, phase_key, field_number);

create index if not exists audit_revision_history_field_created_idx
  on public.audit_revision_history (field_number, created_at desc);

