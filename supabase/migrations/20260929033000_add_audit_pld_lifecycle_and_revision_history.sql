create trigger refresh_audit_pld_after_act_field_update
after update of effective_area_ha on public.master_fields
for each row execute function public.refresh_audit_pld_after_act_field_update();

with latest_run as (
  select run.id, run.completed_at
  from public.act_sync_runs run
  where run.dry_run = false and run.status = 'COMPLETED'
  order by run.completed_at desc nulls last, run.started_at desc
  limit 1
),
audit_phases as (
  select
    audit.field_number,
    'vegetative'::text as phase_key,
    'audit_vegetative'::text as audit_table,
    public.audit_pld_phase_payload(
      'audit_vegetative', 'vegetative', to_jsonb(audit)
    ) as payload
  from public.audit_vegetative audit

  union all

  select
    audit.field_number,
    phase.phase_key,
    'audit_generative',
    public.audit_pld_phase_payload(
      'audit_generative', phase.phase_key, to_jsonb(audit)
    )
  from public.audit_generative audit
  cross join unnest(array[
    'generative_1', 'generative_2', 'generative_3',
    'generative_4', 'generative_5'
  ]) phase(phase_key)

  union all

  select
    audit.field_number,
    'pre_harvest',
    'audit_pre_harvest',
    public.audit_pld_phase_payload(
      'audit_pre_harvest', 'pre_harvest', to_jsonb(audit)
    )
  from public.audit_pre_harvest audit

  union all

  select
    audit.field_number,
    'harvest',
    'audit_harvest',
    public.audit_pld_phase_payload(
      'audit_harvest', 'harvest', to_jsonb(audit)
    )
  from public.audit_harvest audit
),
terminal as (
  select
    phase.*,
    mf.field_number as canonical_field_number,
    mf.effective_area_ha,
    run.id as run_id,
    run.completed_at
  from audit_phases phase
  join public.master_fields mf
    on upper(regexp_replace(btrim(mf.field_number), '[[:space:]]+', '', 'g')) =
      upper(regexp_replace(btrim(phase.field_number), '[[:space:]]+', '', 'g'))
  left join latest_run run on true
  where public.audit_pld_payload_is_terminal(phase.payload)
)
insert into public.audit_pld_lifecycle (
  field_number,
  phase_key,
  status,
  recommendation_payload,
  recommended_flagging,
  effective_area_ha,
  recommended_at,
  confirmed_at,
  confirmed_run_id,
  updated_at
)
select
  terminal.canonical_field_number,
  terminal.phase_key,
  case when terminal.effective_area_ha is not null
      and terminal.effective_area_ha <= 0
    then 'CONFIRMED' else 'PENDING' end,
  terminal.payload,
  public.audit_pld_payload_primary_value(terminal.payload),
  terminal.effective_area_ha,
  now(),
  case when terminal.effective_area_ha is not null
      and terminal.effective_area_ha <= 0
    then coalesce(terminal.completed_at, now()) end,
  case when terminal.effective_area_ha is not null
      and terminal.effective_area_ha <= 0
    then terminal.run_id end,
  now()
from terminal
on conflict (field_number, phase_key) do nothing;

insert into public.audit_revision_history (
  field_number,
  phase_key,
  audit_table,
  event_type,
  new_payload,
  new_flagging,
  lifecycle_status,
  act_sync_run_id,
  created_at
)
select
  lifecycle.field_number,
  lifecycle.phase_key,
  case
    when lifecycle.phase_key = 'vegetative' then 'audit_vegetative'
    when lifecycle.phase_key like 'generative_%' then 'audit_generative'
    when lifecycle.phase_key = 'pre_harvest' then 'audit_pre_harvest'
    else 'audit_harvest'
  end,
  'BACKFILLED',
  lifecycle.recommendation_payload,
  lifecycle.recommended_flagging,
  lifecycle.status,
  lifecycle.confirmed_run_id,
  lifecycle.recommended_at
from public.audit_pld_lifecycle lifecycle
where not exists (
  select 1
  from public.audit_revision_history history
  where history.field_number = lifecycle.field_number
    and history.phase_key = lifecycle.phase_key
);

create or replace function public.get_field_pld_audit_lifecycle(
  p_field_number text
)
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
  with viewer_scope as (
    select
      upper(btrim(users.role)) as role,
      btrim(users.name) as name,
      upper(btrim(users.role)) in ('ADMIN', 'DEV', 'MANAGER') as can_view_all
    from public.app_users users
    where users.id = auth.uid()
      and coalesce(users.is_active, true) = true

    union all

    select 'SERVICE_ROLE', '', true
    where auth.role() = 'service_role'
  ),
  field as (
    select mf.*
    from public.master_fields mf
    where upper(regexp_replace(btrim(mf.field_number), '[[:space:]]+', '', 'g')) =
      upper(regexp_replace(btrim(p_field_number), '[[:space:]]+', '', 'g'))
    order by mf.field_number
    limit 1
  ),
  allowed as (
    select field.field_number
    from field
    where exists (
      select 1
      from viewer_scope scope
      where scope.can_view_all
        or (
          scope.role = 'SPV'
          and public.act_monitor_name_matches(field.qa_spv, scope.name)
        )
        or (
          scope.role = 'FI'
          and public.act_monitor_name_matches(field.qa_fi, scope.name)
        )
    )
  )
  select jsonb_build_object(
    'field_number', (select field_number from allowed),
    'viewer_role', coalesce((select role from viewer_scope limit 1), 'NONE'),
    'can_revise', coalesce((
      select role in ('ADMIN', 'DEV', 'MANAGER', 'FI', 'SERVICE_ROLE')
      from viewer_scope
      limit 1
    ), false),
    'statuses', coalesce((
      select jsonb_agg(
        jsonb_build_object(
          'phase_key', lifecycle.phase_key,
          'status', lifecycle.status,
          'recommended_flagging', lifecycle.recommended_flagging,
          'active_flagging', lifecycle.active_flagging,
          'effective_area_ha', lifecycle.effective_area_ha,
          'recommended_at', lifecycle.recommended_at,
          'confirmed_at', lifecycle.confirmed_at,
          'confirmed_run_id', lifecycle.confirmed_run_id,
          'revised_at', lifecycle.revised_at,
          'updated_at', lifecycle.updated_at,
          'locked', lifecycle.status = 'CONFIRMED'
        )
        order by case lifecycle.phase_key
          when 'vegetative' then 1
          when 'generative_1' then 2
          when 'generative_2' then 3
          when 'generative_3' then 4
          when 'generative_4' then 5
          when 'generative_5' then 6
          when 'pre_harvest' then 7
          else 8
        end
      )
      from public.audit_pld_lifecycle lifecycle
      join allowed on upper(regexp_replace(btrim(allowed.field_number), '[[:space:]]+', '', 'g')) =
        upper(regexp_replace(btrim(lifecycle.field_number), '[[:space:]]+', '', 'g'))
    ), '[]'::jsonb),
    'history', coalesce((
      select jsonb_agg(to_jsonb(item) order by item.created_at desc)
      from (
        select
          history.id,
          history.phase_key,
          history.event_type,
          history.old_payload,
          history.new_payload,
          history.old_flagging,
          history.new_flagging,
          history.lifecycle_status,
          history.actor_name,
          history.actor_role,
          history.act_sync_run_id,
          history.created_at
        from public.audit_revision_history history
        join allowed on upper(regexp_replace(btrim(allowed.field_number), '[[:space:]]+', '', 'g')) =
          upper(regexp_replace(btrim(history.field_number), '[[:space:]]+', '', 'g'))
        order by history.created_at desc
        limit 100
      ) item
    ), '[]'::jsonb)
  );
$$;

revoke all on function public.get_field_pld_audit_lifecycle(text)
