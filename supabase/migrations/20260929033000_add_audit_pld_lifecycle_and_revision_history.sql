create or replace function public.audit_pld_phase_payload(
  p_table text,
  p_phase text,
  p_row jsonb
)
returns jsonb
language plpgsql
immutable
set search_path = ''
as $$
declare
  v_checkpoint text;
begin
  if p_row is null then return '{}'::jsonb; end if;

  if p_table = 'audit_vegetative' then
    return jsonb_strip_nulls(jsonb_build_object(
      'date', coalesce(p_row -> 'audit_date_user', p_row -> 'date_of_audit', p_row -> 'submitted_at'),
      'decision', coalesce(p_row -> 'decision', p_row -> 'final_decision'),
      'action_needed', p_row -> 'action_needed',
      'flagging', coalesce(p_row -> 'flagging', p_row -> 'final_flagging'),
      'pld_reason', p_row -> 'pld_reason',
      'remarks', p_row -> 'remarks'
    ));
  end if;

  if p_table = 'audit_generative' then
    v_checkpoint := split_part(p_phase, '_', 2);
    return jsonb_strip_nulls(jsonb_build_object(
      'date', coalesce(
        p_row -> ('date_of_audit_' || v_checkpoint),
        p_row -> ('submitted_at_' || v_checkpoint)
      ),
      'decision', p_row -> ('final_decision_' || v_checkpoint),
      'action_needed', p_row -> ('action_needed_' || v_checkpoint),
      'flagging', coalesce(
        p_row -> ('final_flagging_' || v_checkpoint),
        p_row -> ('flagging_' || v_checkpoint),
        case when v_checkpoint = '3' then p_row -> 'flagging' end
      ),
      'remarks', coalesce(
        p_row -> ('remarks_' || v_checkpoint),
        p_row -> ('remark_' || v_checkpoint)
      )
    ));
  end if;

  if p_table = 'audit_pre_harvest' then
    return jsonb_strip_nulls(jsonb_build_object(
      'date', coalesce(p_row -> 'audit_date', p_row -> 'date_of_audit', p_row -> 'submitted_at'),
      'decision', coalesce(p_row -> 'final_decision', p_row -> 'decision'),
      'action_needed', p_row -> 'action_needed',
      'flagging', coalesce(p_row -> 'final_flagging', p_row -> 'flagging'),
      'discard_area', coalesce(p_row -> 'discard_area', p_row -> 'discard_area_ha'),
      'discard_reason', p_row -> 'discard_reason',
      'remarks', p_row -> 'remarks'
    ));
  end if;

  if p_table = 'audit_harvest' then
    return jsonb_strip_nulls(jsonb_build_object(
      'date', coalesce(p_row -> 'date_of_audit', p_row -> 'audit_date', p_row -> 'submitted_at'),
      'decision', coalesce(p_row -> 'final_decision', p_row -> 'status_downgrade'),
      'action_needed', p_row -> 'action_needed',
      'flagging', coalesce(
        p_row -> 'final_flagging',
        p_row -> 'downgrade_flagging',
        p_row -> 'flagging'
      ),
      'remarks', p_row -> 'remarks'
    ));
  end if;

  return '{}'::jsonb;
end;
$$;

revoke all on function public.audit_pld_phase_payload(text, text, jsonb)
