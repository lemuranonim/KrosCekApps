create or replace function public.audit_pld_payload_is_terminal(p_payload jsonb)
returns boolean
language plpgsql
immutable
set search_path = ''
as $$
declare
  v_key text;
  v_value text;
begin
  for v_key, v_value in
    select entry.key, upper(btrim(entry.value #>> '{}'))
    from jsonb_each(coalesce(p_payload, '{}'::jsonb)) entry
    where entry.key in ('decision', 'action_needed', 'flagging')
  loop
    if v_value = '' or v_value like '%PARTIAL%' then continue; end if;
    if v_value like '%PLD%' or v_value like '%DISCARD%' then return true; end if;
    if v_key = 'decision' and v_value = 'D' then return true; end if;
    if v_key = 'action_needed' and v_value in ('F', 'G') then return true; end if;
  end loop;
  return false;
end;
$$;

create or replace function public.audit_pld_payload_active_flag(p_payload jsonb)
returns text
language sql
immutable
set search_path = ''
as $$
  select case
    when upper(btrim(coalesce(p_payload ->> 'flagging', ''))) in ('GF', 'RFI', 'RFD')
      then upper(btrim(p_payload ->> 'flagging'))
    else null
  end;
$$;

create or replace function public.audit_pld_payload_primary_value(p_payload jsonb)
returns text
language sql
immutable
set search_path = ''
as $$
  select nullif(btrim(coalesce(
    p_payload ->> 'flagging',
    p_payload ->> 'decision',
    p_payload ->> 'action_needed'
  )), '');
$$;

