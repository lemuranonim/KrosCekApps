create or replace function public.guard_confirmed_act_pld_audit()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_phase text;
  v_field_number text := coalesce(new.field_number, old.field_number);
begin
  if current_setting('app.audit_pld_bypass', true) = 'on' then
    if tg_op = 'DELETE' then return old; end if;
    return new;
  end if;

  foreach v_phase in array public.audit_pld_phase_keys(tg_table_name) loop
    if public.audit_pld_phase_payload(tg_table_name, v_phase, to_jsonb(old))
       is distinct from
       public.audit_pld_phase_payload(tg_table_name, v_phase, to_jsonb(new))
       and exists (
         select 1
         from public.audit_pld_lifecycle lifecycle
         where upper(regexp_replace(btrim(lifecycle.field_number), '[[:space:]]+', '', 'g')) =
           upper(regexp_replace(btrim(v_field_number), '[[:space:]]+', '', 'g'))
           and lifecycle.phase_key = v_phase
           and lifecycle.status = 'CONFIRMED'
       ) then
      raise exception using
        errcode = 'P0001',
        message = format(
          'PLD_ACT_CONFIRMED_LOCKED:%s:%s',
          v_field_number,
          v_phase
        );
    end if;
  end loop;

  if tg_op = 'DELETE' then return old; end if;
  return new;
end;
$$;

revoke all on function public.guard_confirmed_act_pld_audit()
  from public, anon, authenticated;
grant execute on function public.guard_confirmed_act_pld_audit()
  to service_role;

create or replace function public.track_audit_pld_revision()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_phase text;
  v_field_number text := new.field_number;
  v_canonical_field_number text;
  v_old_payload jsonb;
  v_new_payload jsonb;
  v_old_terminal boolean;
  v_new_terminal boolean;
  v_active_flag text;
  v_primary_value text;
  v_effective numeric;
  v_status text;
  v_actor_name text;
  v_actor_role text;
begin
  select mf.field_number, mf.effective_area_ha
  into v_canonical_field_number, v_effective
  from public.master_fields mf
  where upper(regexp_replace(btrim(mf.field_number), '[[:space:]]+', '', 'g')) =
    upper(regexp_replace(btrim(v_field_number), '[[:space:]]+', '', 'g'))
  order by mf.field_number
  limit 1;

  v_field_number := coalesce(v_canonical_field_number, v_field_number);

  select u.name, upper(btrim(u.role))
  into v_actor_name, v_actor_role
  from public.app_users u
  where u.id = auth.uid()
  limit 1;

  foreach v_phase in array public.audit_pld_phase_keys(tg_table_name) loop
    v_old_payload := case when tg_op = 'INSERT' then '{}'::jsonb
      else public.audit_pld_phase_payload(tg_table_name, v_phase, to_jsonb(old)) end;
    v_new_payload := public.audit_pld_phase_payload(
      tg_table_name,
      v_phase,
      to_jsonb(new)
    );

    if v_old_payload is not distinct from v_new_payload then continue; end if;

    v_old_terminal := public.audit_pld_payload_is_terminal(v_old_payload);
    v_new_terminal := public.audit_pld_payload_is_terminal(v_new_payload);
    v_active_flag := public.audit_pld_payload_active_flag(v_new_payload);
    v_primary_value := public.audit_pld_payload_primary_value(v_new_payload);
    v_status := null;

    if v_new_terminal then
      v_status := case when v_effective is not null and v_effective <= 0
        then 'CONFIRMED' else 'PENDING' end;

      insert into public.audit_pld_lifecycle (
        field_number,
        phase_key,
        status,
        recommendation_payload,
        recommended_flagging,
        active_flagging,
        effective_area_ha,
        recommended_at,
        recommended_by,
        confirmed_at,
        confirmed_run_id,
        revised_at,
        revised_by,
        updated_at
      ) values (
        v_field_number,
        v_phase,
        v_status,
        v_new_payload,
        v_primary_value,
        null,
        v_effective,
        now(),
        auth.uid(),
        case when v_status = 'CONFIRMED' then now() end,
        case when v_status = 'CONFIRMED' then (
          select r.id
          from public.act_sync_runs r
          where r.dry_run = false and r.status = 'COMPLETED'
          order by r.completed_at desc nulls last, r.started_at desc
          limit 1
        ) end,
        null,
        null,
        now()
      )
      on conflict (field_number, phase_key) do update set
        status = excluded.status,
        recommendation_payload = excluded.recommendation_payload,
        recommended_flagging = excluded.recommended_flagging,
        active_flagging = null,
        effective_area_ha = excluded.effective_area_ha,
        recommended_at = case
          when public.audit_pld_lifecycle.status = 'UPDATED'
            then excluded.recommended_at
          else public.audit_pld_lifecycle.recommended_at
        end,
        recommended_by = case
          when public.audit_pld_lifecycle.status = 'UPDATED'
            then excluded.recommended_by
          else public.audit_pld_lifecycle.recommended_by
        end,
        confirmed_at = excluded.confirmed_at,
        confirmed_run_id = excluded.confirmed_run_id,
        revised_at = null,
        revised_by = null,
        updated_at = now();
    elsif v_old_terminal and v_active_flag is not null and v_effective > 0 then
      v_status := 'UPDATED';
      update public.audit_pld_lifecycle
      set status = 'UPDATED',
          active_flagging = v_active_flag,
          effective_area_ha = v_effective,
          revised_at = now(),
          revised_by = auth.uid(),
          updated_at = now()
      where field_number = v_field_number
        and phase_key = v_phase;
    else
      select lifecycle.status
      into v_status
      from public.audit_pld_lifecycle lifecycle
      where lifecycle.field_number = v_field_number
        and lifecycle.phase_key = v_phase;
    end if;

    insert into public.audit_revision_history (
      field_number,
      phase_key,
      audit_table,
      event_type,
      old_payload,
      new_payload,
      old_flagging,
      new_flagging,
      lifecycle_status,
      actor_id,
      actor_name,
      actor_role
    ) values (
      v_field_number,
      v_phase,
      tg_table_name,
      case when tg_op = 'INSERT' then 'CREATED' else 'UPDATED' end,
      v_old_payload,
      v_new_payload,
      public.audit_pld_payload_primary_value(v_old_payload),
      v_primary_value,
      v_status,
      auth.uid(),
      v_actor_name,
      v_actor_role
    );
  end loop;

  return new;
end;
$$;

revoke all on function public.track_audit_pld_revision()
  from public, anon, authenticated;
grant execute on function public.track_audit_pld_revision()
  to service_role;

do $$
declare
  v_table text;
begin
  foreach v_table in array array[
    'audit_vegetative',
    'audit_generative',
    'audit_pre_harvest',
    'audit_harvest'
  ] loop
    execute format(
      'drop trigger if exists %I on public.%I',
      'guard_confirmed_act_pld_' || v_table,
      v_table
    );
    execute format(
      'create trigger %I before update or delete on public.%I for each row execute function public.guard_confirmed_act_pld_audit()',
      'guard_confirmed_act_pld_' || v_table,
      v_table
    );
    execute format(
      'drop trigger if exists %I on public.%I',
      'track_audit_pld_revision_' || v_table,
      v_table
    );
    execute format(
      'create trigger %I after insert or update on public.%I for each row execute function public.track_audit_pld_revision()',
      'track_audit_pld_revision_' || v_table,
      v_table
    );
  end loop;
end;
$$;

create or replace function public.refresh_audit_pld_lifecycle_for_field(
  p_field_number text,
  p_run_id uuid default null
)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_effective numeric;
  v_item record;
  v_payload jsonb;
  v_active_flag text;
  v_new_status text;
  v_changed integer := 0;
begin
  select mf.effective_area_ha
  into v_effective
  from public.master_fields mf
  where upper(regexp_replace(btrim(mf.field_number), '[[:space:]]+', '', 'g')) =
    upper(regexp_replace(btrim(p_field_number), '[[:space:]]+', '', 'g'))
  order by mf.field_number
  limit 1;

  for v_item in
    select lifecycle.*
    from public.audit_pld_lifecycle lifecycle
    where upper(regexp_replace(btrim(lifecycle.field_number), '[[:space:]]+', '', 'g')) =
      upper(regexp_replace(btrim(p_field_number), '[[:space:]]+', '', 'g'))
  loop
    if v_item.phase_key = 'vegetative' then
      select public.audit_pld_phase_payload(
        'audit_vegetative', v_item.phase_key, to_jsonb(audit)
      ) into v_payload
      from public.audit_vegetative audit
      where upper(regexp_replace(btrim(audit.field_number), '[[:space:]]+', '', 'g')) =
        upper(regexp_replace(btrim(p_field_number), '[[:space:]]+', '', 'g'))
      limit 1;
    elsif v_item.phase_key like 'generative_%' then
      select public.audit_pld_phase_payload(
        'audit_generative', v_item.phase_key, to_jsonb(audit)
      ) into v_payload
      from public.audit_generative audit
      where upper(regexp_replace(btrim(audit.field_number), '[[:space:]]+', '', 'g')) =
        upper(regexp_replace(btrim(p_field_number), '[[:space:]]+', '', 'g'))
      limit 1;
    elsif v_item.phase_key = 'pre_harvest' then
      select public.audit_pld_phase_payload(
        'audit_pre_harvest', v_item.phase_key, to_jsonb(audit)
      ) into v_payload
      from public.audit_pre_harvest audit
      where upper(regexp_replace(btrim(audit.field_number), '[[:space:]]+', '', 'g')) =
        upper(regexp_replace(btrim(p_field_number), '[[:space:]]+', '', 'g'))
      limit 1;
    else
      select public.audit_pld_phase_payload(
        'audit_harvest', v_item.phase_key, to_jsonb(audit)
      ) into v_payload
      from public.audit_harvest audit
      where upper(regexp_replace(btrim(audit.field_number), '[[:space:]]+', '', 'g')) =
        upper(regexp_replace(btrim(p_field_number), '[[:space:]]+', '', 'g'))
      limit 1;
    end if;

    v_payload := coalesce(v_payload, '{}'::jsonb);
    v_active_flag := public.audit_pld_payload_active_flag(v_payload);

    if public.audit_pld_payload_is_terminal(v_payload) then
      v_new_status := case when v_effective is not null and v_effective <= 0
        then 'CONFIRMED' else 'PENDING' end;
    elsif v_active_flag is not null and v_effective > 0 then
      v_new_status := 'UPDATED';
    else
      continue;
    end if;

    if v_item.status is distinct from v_new_status
       or v_item.effective_area_ha is distinct from v_effective then
      update public.audit_pld_lifecycle
      set status = v_new_status,
          active_flagging = case when v_new_status = 'UPDATED'
            then v_active_flag else null end,
          effective_area_ha = v_effective,
          confirmed_at = case when v_new_status = 'CONFIRMED'
            then now() else null end,
          confirmed_run_id = case when v_new_status = 'CONFIRMED'
            then p_run_id else null end,
          updated_at = now()
      where upper(regexp_replace(btrim(field_number), '[[:space:]]+', '', 'g')) =
        upper(regexp_replace(btrim(p_field_number), '[[:space:]]+', '', 'g'))
        and phase_key = v_item.phase_key;

      insert into public.audit_revision_history (
        field_number,
        phase_key,
        audit_table,
        event_type,
        old_payload,
        new_payload,
        old_flagging,
        new_flagging,
        lifecycle_status,
        act_sync_run_id
      ) values (
        p_field_number,
        v_item.phase_key,
        case
          when v_item.phase_key = 'vegetative' then 'audit_vegetative'
          when v_item.phase_key like 'generative_%' then 'audit_generative'
          when v_item.phase_key = 'pre_harvest' then 'audit_pre_harvest'
          else 'audit_harvest'
        end,
        case when v_new_status = 'CONFIRMED'
          then 'ACT_CONFIRMED' else 'ACT_REOPENED' end,
        v_item.recommendation_payload,
        v_payload,
        v_item.recommended_flagging,
        public.audit_pld_payload_primary_value(v_payload),
        v_new_status,
        p_run_id
      );
      v_changed := v_changed + 1;
    end if;
  end loop;

  return v_changed;
end;
$$;

revoke all on function public.refresh_audit_pld_lifecycle_for_field(text, uuid)
