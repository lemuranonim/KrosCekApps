create table if not exists public.act_sync_runs (
  id uuid primary key default gen_random_uuid(),
  status text not null default 'EXTRACTING'
    check (status in ('EXTRACTING', 'WAITING_EXPORT', 'VALIDATING', 'READY', 'APPLYING', 'COMPLETED', 'BLOCKED', 'FAILED')),
  dry_run boolean not null default true,
  source_from date not null,
  source_to date not null,
  requested_sources text[] not null default array['FC', 'PS', 'SC']::text[],
  requested_by uuid,
  source_counts jsonb not null default '{}'::jsonb,
  source_meta jsonb not null default '{}'::jsonb,
  summary jsonb not null default '{}'::jsonb,
  error_message text,
  started_at timestamptz not null default now(),
  completed_at timestamptz,
  created_at timestamptz not null default now(),
  constraint act_sync_runs_date_order check (source_from <= source_to)
);

create table if not exists public.act_sync_rows (
  id bigint generated by default as identity primary key,
  run_id uuid not null references public.act_sync_runs(id) on delete cascade,
  source_type text not null check (source_type in ('FC', 'PS', 'SC')),
  source_row integer not null,
  field_number_raw text,
  field_number_norm text,
  raw_payload jsonb not null default '{}'::jsonb,
  source_payload jsonb not null default '{}'::jsonb,
  row_hash text not null,
  validation_errors text[] not null default '{}'::text[],
  created_at timestamptz not null default now(),
  unique (run_id, source_type, source_row)
);

create table if not exists public.act_sync_changes (
  id bigint generated by default as identity primary key,
  run_id uuid not null references public.act_sync_runs(id) on delete cascade,
  field_number_norm text not null,
  source_type text check (source_type in ('FC', 'PS', 'SC')),
  change_kind text not null check (
    change_kind in (
      'INSERT',
      'UPDATE',
      'UNCHANGED',
      'INVALID',
      'CONFLICT_SOURCE_DUPLICATE',
      'CONFLICT_KC_DUPLICATE',
      'MISSING_SOURCE'
    )
  ),
  current_payload jsonb,
  source_payload jsonb,
  changed_columns jsonb not null default '{}'::jsonb,
  validation_errors text[] not null default '{}'::text[],
  applied boolean not null default false,
  applied_at timestamptz,
  apply_error text,
  created_at timestamptz not null default now(),
  unique (run_id, field_number_norm)
);

create table if not exists public.act_master_fields_change_log (
  id bigint generated by default as identity primary key,
  run_id uuid not null references public.act_sync_runs(id) on delete restrict,
  field_number text not null,
  operation text not null check (operation in ('INSERT', 'UPDATE')),
  source_type text not null check (source_type in ('FC', 'PS', 'SC')),
  changed_columns jsonb not null default '{}'::jsonb,
  before_payload jsonb,
  after_payload jsonb not null,
  applied_at timestamptz not null default now()
);

create index if not exists act_sync_runs_started_idx
  on public.act_sync_runs (started_at desc);

create index if not exists act_sync_rows_run_field_idx
  on public.act_sync_rows (run_id, field_number_norm);

create index if not exists act_sync_changes_run_kind_idx
  on public.act_sync_changes (run_id, change_kind);

create index if not exists act_master_fields_change_log_field_idx
  on public.act_master_fields_change_log (field_number, applied_at desc);

alter table public.act_sync_runs enable row level security;
alter table public.act_sync_rows enable row level security;
alter table public.act_sync_changes enable row level security;
alter table public.act_master_fields_change_log enable row level security;

revoke all on table public.act_sync_runs from anon, authenticated;
revoke all on table public.act_sync_rows from anon, authenticated;
revoke all on table public.act_sync_changes from anon, authenticated;
revoke all on table public.act_master_fields_change_log from anon, authenticated;

grant all on table public.act_sync_runs to service_role;
grant all on table public.act_sync_rows to service_role;
grant all on table public.act_sync_changes to service_role;
grant all on table public.act_master_fields_change_log to service_role;
grant usage, select on all sequences in schema public to service_role;

