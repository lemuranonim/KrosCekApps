create or replace function public.apply_act_master_fields_sync(
  p_run_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_run public.act_sync_runs%rowtype;
  v_change public.act_sync_changes%rowtype;
  v_before public.master_fields%rowtype;
  v_after public.master_fields%rowtype;
  v_patch jsonb;
  v_match_count integer;
  v_inserted integer := 0;
  v_updated integer := 0;
begin
  select *
  into v_run
  from public.act_sync_runs
  where id = p_run_id
  for update;

  if not found then
    raise exception 'ACT sync run not found: %', p_run_id;
  end if;
  if v_run.dry_run then
    raise exception 'Dry-run cannot be applied: %', p_run_id;
  end if;
  if v_run.status <> 'READY' then
    raise exception 'ACT sync run must be READY, current status: %', v_run.status;
  end if;
  if exists (
    select 1
    from public.act_sync_changes
    where run_id = p_run_id
      and change_kind in ('INVALID', 'CONFLICT_SOURCE_DUPLICATE', 'CONFLICT_KC_DUPLICATE')
  ) then
    raise exception 'ACT sync run contains blocking validation errors: %', p_run_id;
  end if;

  update public.act_sync_runs
  set status = 'APPLYING'
  where id = p_run_id;

  for v_change in
    select *
    from public.act_sync_changes
    where run_id = p_run_id
      and change_kind in ('INSERT', 'UPDATE')
      and applied = false
    order by id
  loop
    select count(*)
    into v_match_count
    from public.master_fields mf
    where upper(btrim(mf.field_number)) = v_change.field_number_norm;

    if v_match_count > 1 then
      raise exception 'Duplicate normalized field_number in KC during apply: %',
        v_change.field_number_norm;
    end if;

    if v_change.change_kind = 'UPDATE' then
      if v_match_count = 0 then
        raise exception 'KC field disappeared before apply: %', v_change.field_number_norm;
      end if;

      select mf.*
      into v_before
      from public.master_fields mf
      where upper(btrim(mf.field_number)) = v_change.field_number_norm
      for update;

      v_patch := v_change.source_payload - 'field_number';
      if lower(coalesce(v_before.geometry_source, '')) in ('manual', 'kc_manual') then
        v_patch := v_patch - 'geometry_wkt';
      end if;

      select *
      into v_after
      from jsonb_populate_record(v_before, v_patch);

      update public.master_fields
      set farmer_name = v_after.farmer_name,
          grower = v_after.grower,
          hybrid = v_after.hybrid,
          total_area_planted_ha = v_after.total_area_planted_ha,
          discard_area_ha = v_after.discard_area_ha,
          effective_area_ha = v_after.effective_area_ha,
          planting_date_pdn = v_after.planting_date_pdn,
          hamlet_dusun = v_after.hamlet_dusun,
          village_desa = v_after.village_desa,
          sub_district_kec = v_after.sub_district_kec,
          district_kab = v_after.district_kab,
          fa = v_after.fa,
          field_spv = v_after.field_spv,
          coordinate = v_after.coordinate,
          region = v_after.region,
          area_manager = v_after.area_manager,
          type = v_after.type,
          prov = v_after.prov,
          planting_ratio = v_after.planting_ratio,
          planting_space = v_after.planting_space,
          geometry_wkt = v_after.geometry_wkt,
          geometry_source = case
            when v_patch ? 'geometry_wkt' then 'ACT'
            else v_before.geometry_source
          end
      where field_number = v_before.field_number
      returning * into v_after;

      v_updated := v_updated + 1;
    else
      if v_match_count > 0 then
        raise exception 'ACT insert became an existing KC field before apply: %',
          v_change.field_number_norm;
      end if;

      v_patch := v_change.source_payload
        || jsonb_build_object(
          'field_number', v_change.field_number_norm,
          'is_active', true,
          'geometry_source', case
            when v_change.source_payload ? 'geometry_wkt' then 'ACT'
            else null
          end
        );

      select *
      into v_after
      from jsonb_populate_record(null::public.master_fields, v_patch);

      insert into public.master_fields (
        field_number,
        farmer_name,
        grower,
        hybrid,
        total_area_planted_ha,
        discard_area_ha,
        effective_area_ha,
        planting_date_pdn,
        hamlet_dusun,
        village_desa,
        sub_district_kec,
        district_kab,
        fa,
        field_spv,
        coordinate,
        region,
        area_manager,
        type,
        prov,
        planting_ratio,
        planting_space,
        geometry_wkt,
        geometry_source,
        is_active
      ) values (
        v_after.field_number,
        v_after.farmer_name,
        v_after.grower,
        v_after.hybrid,
        v_after.total_area_planted_ha,
        v_after.discard_area_ha,
        v_after.effective_area_ha,
        v_after.planting_date_pdn,
        v_after.hamlet_dusun,
        v_after.village_desa,
        v_after.sub_district_kec,
        v_after.district_kab,
        v_after.fa,
        v_after.field_spv,
        v_after.coordinate,
        v_after.region,
        v_after.area_manager,
        v_after.type,
        v_after.prov,
        v_after.planting_ratio,
        v_after.planting_space,
        v_after.geometry_wkt,
        v_after.geometry_source,
        v_after.is_active
      )
      returning * into v_after;

      v_before := null;
      v_inserted := v_inserted + 1;
    end if;

    insert into public.act_master_fields_change_log (
      run_id,
      field_number,
      operation,
      source_type,
      changed_columns,
      before_payload,
      after_payload
    ) values (
      p_run_id,
      v_change.field_number_norm,
      v_change.change_kind,
      v_change.source_type,
      v_change.changed_columns,
      case
        when v_change.change_kind = 'UPDATE'
          then public.act_master_fields_sync_snapshot(v_before)
        else null
      end,
      public.act_master_fields_sync_snapshot(v_after)
    );

    update public.act_sync_changes
    set applied = true,
        applied_at = now(),
        apply_error = null
    where id = v_change.id;
  end loop;

  update public.act_sync_runs
  set status = 'COMPLETED',
      completed_at = now(),
      summary = summary || jsonb_build_object(
        'applied_insert', v_inserted,
        'applied_update', v_updated
      )
  where id = p_run_id;

  return jsonb_build_object(
    'run_id', p_run_id,
    'inserted', v_inserted,
    'updated', v_updated
  );
end;
$$;

revoke all on function public.apply_act_master_fields_sync(uuid)
  from public, anon, authenticated;
grant execute on function public.apply_act_master_fields_sync(uuid)
  to service_role;

